import { test, expect } from '@playwright/test'

test('Part 2 SMA reference, persisted backtest and paper accounting through real controls', async ({ page }) => {
  test.skip(process.env.SMOKE_TEST !== '1', 'Run isolated SmokeTest')
  const errors=[]; page.on('pageerror', error=>errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Short SMA window').fill('2')
  await page.getByLabel('Long SMA window').fill('3')
  await page.getByRole('button',{name:'SMA reference',exact:true}).click()
  await expect(page.getByText('Synthetic SMA reference · seven completed candles · not live market data')).toBeVisible()
  await page.getByLabel('Inspect candle',{exact:true}).selectOption({label:'2026-11-09T15:04:00Z'})
  await expect(page.getByLabel('Candle details')).toContainText('SMA 2: 16.00 · SMA 3: 13.00')
  await page.screenshot({path:'../docs/screenshots/part2-sma-reference.png',fullPage:true})
  const panel=page.getByRole('region',{name:'Simulation and backtesting'})
  await panel.getByRole('button',{name:'Run backtest',exact:true}).click()
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,032.00')
  await expect(panel.getByRole('table',{name:'Paper fill history'})).toContainText('$1.00')
  await expect(panel.getByRole('table',{name:'Paper fill history'})).toContainText('$9.00')
  const saved = await panel.getByLabel('Saved paper account').inputValue()
  await page.reload()
  await panel.getByLabel('Saved paper account').selectOption(saved)
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,032.00')
  await panel.getByLabel('Strategy short window').fill('0')
  await panel.getByRole('button',{name:'Run backtest',exact:true}).click()
  await expect(panel.getByRole('alert')).toContainText('whole-number')
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,032.00')
  await panel.getByLabel('Strategy short window').fill('2')
  await page.getByLabel('Market symbol').selectOption('BTC-USD')
  await panel.getByRole('button',{name:'Create paper account',exact:true}).click()
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,000.00')
  const start=Math.floor(Date.now()/1000)+3
  const ingest=async(offset,price)=>{
    const response=await page.request.post('/api/test/ingest',{data:[{payload:{id:'BTC-USD',time:(start+offset)*1000,price},received:start+offset+1}]})
    expect(response.ok()).toBeTruthy()
  }
  await panel.getByRole('button',{name:'Buy paper',exact:true}).click()
  await expect(panel.getByRole('table',{name:'Paper order history'})).toContainText('pending')
  await ingest(0,100)
  await expect(panel.getByTestId('paper-cash')).toHaveText('$600.00')
  await ingest(60,110); await ingest(120,110)
  await expect(panel.getByTestId('paper-summary')).toContainText('$40.00')
  await panel.getByLabel('Manual paper quantity').fill('1')
  await panel.getByRole('button',{name:'Sell paper',exact:true}).click()
  await ingest(130,110)
  await expect(panel.getByTestId('paper-cash')).toHaveText('$710.00')
  await ingest(180,95); await ingest(240,95)
  await expect(panel.getByTestId('paper-summary')).toContainText('-$15.00')
  await panel.getByRole('button',{name:'Close paper',exact:true}).click()
  await ingest(250,105)
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,025.00')
  await panel.getByRole('button',{name:'Retry last request',exact:true}).click()
  await expect(panel.getByRole('table',{name:'Paper fill history'}).locator('tbody tr')).toHaveCount(3)
  await panel.getByRole('button',{name:'Sell paper',exact:true}).click()
  await expect(panel.getByRole('table',{name:'Paper order history'})).toContainText('Insufficient shares')
  await page.screenshot({path:'../docs/screenshots/part2-accounting.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  await page.screenshot({path:'../docs/screenshots/part2-mobile.png',fullPage:true})
  expect(errors).toEqual([])
})

test('persisted paper account after backend restart', async ({page}) => {
  test.skip(process.env.SMOKE_RESTART !== '1','Run by SmokeTest after restart')
  await page.goto('/')
  const data=await (await page.request.get('/api/paper/accounts')).json()
  const account=data.accounts.find(a=>a.config.symbol==='BTC-USD' && a.config.source==='live')
  expect(account).toBeTruthy()
  await page.getByLabel('Saved paper account').selectOption(account.id)
  await expect(page.getByTestId('paper-cash')).toHaveText('$1,025.00')
  await expect(page.getByRole('table',{name:'Paper fill history'}).locator('tbody tr')).toHaveCount(3)
  await expect(page.getByRole('table',{name:'Paper order history'})).toContainText('Insufficient shares')
})
