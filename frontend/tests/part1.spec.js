import { test, expect } from '@playwright/test'

test('Part 1 real UI, API, SQLite, CSV, timeframes, replay and disconnected feed', async ({ page }) => {
  test.skip(process.env.SMOKE_TEST !== '1', 'Run python scripts/smoke_test.py for isolated services and fixtures')
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Apple Inc.', exact: true })).toBeVisible()
  await expect(page.getByText('Waiting for market observations')).toBeVisible()
  await page.getByRole('button', { name: 'CSV sample', exact: true }).click()
  await expect(page.getByText('Synthetic CSV sample · November 9, 2026 · not live market data')).toBeVisible()
  await page.getByLabel('Inspect candle', { exact: true }).selectOption({ label: '2026-11-09T14:31:00Z' })
  await expect(page.getByTestId('inspected-close')).toHaveText('C 101.00')
  await expect(page.getByTestId('inspected-volume')).toHaveText('V 850')
  expect((await (await page.request.get('/api/observations/AAPL')).json()).length).toBe(0)
  await page.getByLabel('Chart timeframe').selectOption('5m')
  await expect(page.getByTestId('inspected-volume')).toHaveText('V 3.55K')
  await expect(page.getByLabel('Candle details')).toContainText('Coverage 3/5 minutes')
  await page.getByLabel('Chart timeframe').selectOption('1d')
  await expect(page.getByLabel('Candle details')).toContainText('Coverage 3/390 minutes')
  await page.getByLabel('Chart timeframe').selectOption('1m')

  const start = Date.parse('2026-11-09T15:00:00Z')/1000
  const events = [[-1,99,1000],[5,100,1004],[50,101,1011],[20,103,1009]].map(([offset, price, volume], index) => ({ payload: { id:'AAPL', time:(start+offset)*1000, price, day_volume:volume }, received:start+index+55 }))
  const result = await page.request.post('/api/test/ingest', { data: events })
  expect(result.ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Live feed', exact: true }).click()
  await page.getByLabel('Inspect candle', { exact:true }).selectOption({ label:'2026-11-09T14:59:00Z' })
  await expect(page.getByTestId('inspected-volume')).toHaveText('V Unknown')
  await page.getByLabel('Replay range start UTC').fill('2026-11-09T15:00')
  await page.getByLabel('Replay range end UTC').fill('2026-11-09T15:01')
  await page.getByRole('button', { name: 'Apply range', exact: true }).click()
  await expect(page.getByTestId('inspected-volume')).toHaveText('V 11')
  await expect(page.getByTestId('inspected-close')).toHaveText('C 101.00')
  const before = await (await page.request.get('/api/observations/AAPL')).json()
  for (let repeat=0; repeat<2; repeat++) {
    await page.getByRole('button', { name: 'Replay stored', exact: true }).click()
    await expect(page.locator('.replay-clock')).toContainText('Source 2026-11-09T15:00:05Z')
    await expect(page.getByText('Replay complete. Select Live feed to resume.')).toBeVisible()
    await expect(page.locator('.replay-clock')).toContainText('Source 2026-11-09T15:00:20Z')
    await expect(page.getByTestId('inspected-volume')).toHaveText('V 11')
    await expect(page.getByTestId('inspected-close')).toHaveText('C 101.00')
    expect(await (await page.request.get('/api/observations/AAPL')).json()).toEqual(before)
  }
  await page.getByRole('button', { name: 'Reconnect Yahoo', exact: true }).click()
  await expect(page.locator('#source .status')).toContainText('waiting')
  await page.getByRole('button', { name: 'Disconnect Yahoo', exact: true }).click()
  await expect(page.locator('#source .status')).toContainText('offline')
  await expect(page.locator('#source')).toContainText('connected')
  await page.getByLabel('Replay range start UTC').fill('2026-11-09T16:00')
  await page.getByLabel('Replay range end UTC').fill('2026-11-09T15:00')
  await page.getByRole('button', { name: 'Replay stored', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Range end must be after its start')
  await page.getByRole('button', { name: 'Clear range', exact: true }).click()
  await page.getByRole('button', { name: 'CSV sample', exact: true }).click()
  await expect(page.getByText('Synthetic CSV sample · November 9, 2026 · not live market data')).toBeVisible()
  await page.getByRole('button', { name: 'Fit chart' }).click()
  await page.screenshot({ path:'test-results/part1-desktop.png', fullPage:true })
  await page.getByLabel('Search markets').fill('Microsoft')
  await expect(page.locator('.watch-row')).toHaveCount(1)
  await page.locator('.watch-row').click()
  await expect(page.getByRole('heading', { name:'Microsoft Corporation', exact:true })).toBeVisible()
  await page.getByLabel('Search markets').fill('')
  await page.setViewportSize({ width:390, height:844 })
  await expect(page.getByRole('button', { name:'Reconnect Yahoo', exact:true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path:'test-results/part1-mobile.png', fullPage:true })
  expect(errors).toEqual([])
})

test('persisted offline replay after backend restart', async ({ page }) => {
  test.skip(process.env.SMOKE_RESTART !== '1', 'Run by SmokeTest after backend restart')
  await page.goto('/')
  const before = await (await page.request.get('/api/observations/AAPL')).json()
  expect(before).toHaveLength(4)
  await page.getByLabel('Replay range start UTC').fill('2026-11-09T15:00')
  await page.getByLabel('Replay range end UTC').fill('2026-11-09T15:01')
  for (let repeat=0; repeat<2; repeat++) {
    await page.getByRole('button', { name:'Replay stored', exact:true }).click()
    await expect(page.getByText('Replay complete. Select Live feed to resume.')).toBeVisible()
    await expect(page.getByTestId('inspected-close')).toHaveText('C 101.00')
    await expect(page.getByTestId('inspected-volume')).toHaveText('V 11')
  }
  await expect(page.locator('#source .status')).toContainText('offline')
  expect(await (await page.request.get('/api/observations/AAPL')).json()).toEqual(before)
})

test('optional Yahoo observation reaches SQLite and chart with fresh receipt time', async ({ page }) => {
  test.skip(process.env.LIVE_TEST !== '1', 'Live-provider verification is separate from offline SmokeTest')
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const before = Date.now()/1000
  await page.goto('/')
  await page.getByLabel('Market symbol').selectOption('BTC-USD')
  await expect.poll(async () => {
    const rows = await (await page.request.get('/api/observations/BTC-USD')).json()
    return rows.some(row => row.received_time >= before)
  }, { timeout:45000 }).toBeTruthy()
  await expect(page.locator('.quote strong')).not.toHaveText('—', { timeout:15000 })
  await page.getByRole('button', { name:'Disconnect Yahoo', exact:true }).click()
  await expect(page.locator('#source .status')).toContainText('offline')
  await expect(page.locator('#source')).toContainText('connected')
  const recorded = await (await page.request.get('/api/observations/BTC-USD')).json()
  const latest = recorded.sort((a,b) => a.source_time-b.source_time || a.sequence-b.sequence).at(-1)
  await expect(page.locator('.quote strong')).toHaveText(latest.price.toLocaleString('en-US', { minimumFractionDigits:2, maximumFractionDigits:2 }))
  await page.getByRole('button', { name:'Replay stored', exact:true }).click()
  await expect(page.locator('.replay-clock')).toBeVisible()
  await page.getByRole('button', { name:'Reconnect Yahoo', exact:true }).click()
  await expect(page.locator('#source .status')).toContainText(/waiting|connected/)
  expect(errors).toEqual([])
})
