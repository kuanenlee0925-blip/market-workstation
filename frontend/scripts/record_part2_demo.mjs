import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'

const browser = await chromium.launch()
const context = await browser.newContext({ viewport:{width:1440,height:1000}, recordVideo:{dir:'test-results/part2-video',size:{width:1440,height:1000}} })
const page = await context.newPage()
const pause = ms => page.waitForTimeout(ms)
try {
  await page.goto(process.env.MARKET_BASE_URL)
  await page.getByLabel('Short SMA window').fill('2')
  await page.getByLabel('Long SMA window').fill('3')
  await page.getByRole('button',{name:'SMA reference',exact:true}).click()
  await expect(page.getByText('Synthetic SMA reference · seven completed candles · not live market data')).toBeVisible()
  await page.getByRole('button',{name:'Fit chart'}).click()
  await pause(4000)
  await page.getByLabel('Inspect candle',{exact:true}).selectOption({label:'2026-11-09T15:04:00Z'})
  await pause(3000)
  await page.getByLabel('Inspect candle',{exact:true}).selectOption({label:'2026-11-09T15:06:00Z'})
  await pause(3000)
  const panel=page.getByRole('region',{name:'Simulation and backtesting'})
  await panel.scrollIntoViewIfNeeded()
  await panel.getByRole('button',{name:'Run backtest',exact:true}).click()
  await expect(panel.getByTestId('paper-cash')).toHaveText('$1,032.00')
  await panel.getByTestId('paper-summary').scrollIntoViewIfNeeded()
  await pause(4000)
  await panel.getByRole('table',{name:'Paper fill history'}).scrollIntoViewIfNeeded()
  await pause(4000)
  await page.getByLabel('Market symbol').selectOption('BTC-USD')
  await panel.getByLabel('Backtest dataset').selectOption('recorded')
  await panel.getByLabel('Starting paper cash').fill('100000')
  await panel.getByLabel('Strategy order size').fill('1')
  await panel.getByRole('button',{name:'Run backtest',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Run backtest',exact:true})).toBeEnabled({timeout:60000})
  await expect(panel.locator('.paper-context')).toContainText('recorded Yahoo arrivals; not live')
  const identifier = await panel.getByLabel('Saved paper account').inputValue()
  const result = await (await page.request.get(process.env.MARKET_BASE_URL+'/api/paper/accounts/'+identifier)).json()
  expect(result.fills.length).toBeGreaterThan(0)
  await fs.writeFile(path.resolve('../docs/part2-recorded-result.json'), JSON.stringify({description:'Observed backtest of 600 previously recorded Yahoo BTC-USD arrivals; no new live-source or model request',config:result.config,summary:result.summary,orders:result.orders,fills:result.fills,first_signal:result.signals[0],last_signal:result.signals.at(-1)},null,2)+'\n')
  await panel.getByTestId('paper-summary').scrollIntoViewIfNeeded()
  await pause(5000)
  await panel.getByRole('table',{name:'Paper fill history'}).scrollIntoViewIfNeeded()
  await pause(4000)
  await panel.getByRole('table',{name:'Paper profit and loss history'}).scrollIntoViewIfNeeded()
  await pause(4000)
  await page.screenshot({path:'../docs/screenshots/part2-recorded-backtest.png',fullPage:true})
  await panel.getByTestId('paper-summary').scrollIntoViewIfNeeded()
  await pause(4000)
  await page.close()
  await page.video().saveAs(path.resolve('../docs/part2-demo-2026-11-18.webm'))
} finally {
  await context.close()
  await browser.close()
}
